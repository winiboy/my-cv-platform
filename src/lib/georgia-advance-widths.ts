/**
 * The advance widths of Georgia, the serif `swissFinance` draws in every
 * output, so a generator can size a column to the text it holds instead of
 * guessing: Word splits a word that does not fit its cell, and the Preview's
 * `fit-content` column never does, so the Word cell must be at least as
 * wide as the browser's.
 *
 * Provenance: read on 2026-11-22 from the hmtx and cmap tables of the Windows
 * font files (georgia.ttf, georgiab.ttf, georgiai.ttf; unitsPerEm 2048) for
 * Basic Latin through Latin Extended-B, General Punctuation and the euro sign:
 * every letter fr, en, de and it write. A code point the font does not map is
 * -1 in its range. The table holds advance widths only — metrics, not glyph
 * outlines or any other part of the font software — and the font itself is
 * neither copied nor shipped.
 *
 * Why Georgia's own widths and not Gelasio's (`@fontsource/gelasio`, SIL OFL,
 * the PDF route's metric-compatible stand-in for Georgia): compared over the
 * same ranges, Gelasio's latin and latin-ext subsets match Georgia within one
 * font unit for about 335 of 346 code points per face but not for all — e.g.
 * italic Ó, Ö and Ø (1524 vs 1496), bold ď (1691 vs 1461), ¸ in every face —
 * and Word draws Georgia, so a cell sized from Gelasio could fall short of a
 * German word in Word.
 *
 * Kerning is not applied: both Chromium and Word kern Georgia's pairs closer
 * or not at all, so a width summed here is never narrower than the one either
 * engine draws. A code point outside these ranges is measured as the face's
 * widest glyph, so an unknown character can only widen a measure.
 */


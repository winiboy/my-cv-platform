const WIDEST: Readonly<Record<GeorgiaFace, number>> = {
  regular: Math.max(...ADVANCES.regular.flatMap((range) => range.widths)),
  bold: Math.max(...ADVANCES.bold.flatMap((range) => range.widths)),
  italic: Math.max(...ADVANCES.italic.flatMap((range) => range.widths)),
}

/** One code point's advance in `face`, in font units. */
function advance(face: GeorgiaFace, codePoint: number): number {
  for (const range of ADVANCES[face]) {
    const width = range.widths[codePoint - range.from]
    if (width !== undefined) return width >= 0 ? width : WIDEST[face]
  }
  return WIDEST[face]
}

/**
 * The width, in CSS px, of `text` set on one line in Georgia `face` at `px`,
 * with `trackingEm` of letter spacing after every character, as CSS
 * `letter-spacing` and Word character spacing both add it.
 */
export function georgiaTextWidthPx(text: string, face: GeorgiaFace, px: number, trackingEm = 0): number {
  let units = 0
  let characters = 0
  for (const character of text) {
    units += advance(face, character.codePointAt(0) as number)
    characters += 1
  }
  return (units / UNITS_PER_EM) * px + characters * trackingEm * px
}
